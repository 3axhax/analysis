export const MEDICAL_SOURCE_SQL = `
CREATE TABLE IF NOT EXISTS "medicalSource" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "parentId" integer,
  name text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE "medicalSource" ADD CONSTRAINT medical_source_parent_fk FOREIGN KEY ("parentId") REFERENCES "medicalSource"(id) ON DELETE RESTRICT;
ALTER TABLE "medicalSource" ADD CONSTRAINT medical_source_name_check CHECK (length(trim(name)) > 0);
ALTER TABLE "medicalSource" ADD CONSTRAINT medical_source_metadata_check CHECK (jsonb_typeof(metadata) = 'object');
ALTER TABLE "medicalSource" ADD CONSTRAINT medical_source_self_check CHECK ("parentId" IS NULL OR "parentId" <> id);
CREATE INDEX medical_source_parent_idx ON "medicalSource"("parentId");
CREATE FUNCTION medical_source_check_cycle() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW."parentId" IS DISTINCT FROM OLD."parentId" THEN
    RAISE EXCEPTION 'medical source reparenting is not supported';
  END IF;
  PERFORM pg_advisory_xact_lock(28002001);
  IF NEW."parentId" IS NOT NULL AND EXISTS (
    WITH RECURSIVE ancestors(id, parent_id) AS (
      SELECT id, "parentId" FROM "medicalSource" WHERE id = NEW."parentId"
      UNION
      SELECT s.id, s."parentId" FROM "medicalSource" s JOIN ancestors a ON s.id = a.parent_id
    ) SELECT 1 FROM ancestors WHERE id = NEW.id
  ) THEN RAISE EXCEPTION 'medical source cycle'; END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER medical_source_no_cycle BEFORE INSERT OR UPDATE OF "parentId" ON "medicalSource"
FOR EACH ROW EXECUTE FUNCTION medical_source_check_cycle();
ALTER TABLE "analysisPointMinValue" ADD COLUMN "sourceId" integer REFERENCES "medicalSource"(id) ON DELETE RESTRICT;
ALTER TABLE "analysisPointMaxValue" ADD COLUMN "sourceId" integer REFERENCES "medicalSource"(id) ON DELETE RESTRICT;
ALTER TABLE "analysisResultDescription" ADD COLUMN "sourceId" integer REFERENCES "medicalSource"(id) ON DELETE RESTRICT;
CREATE TABLE IF NOT EXISTS "sourceReferenceInheritance" (
  "sourceId" integer NOT NULL,
  "pointId" integer NOT NULL,
  PRIMARY KEY ("sourceId", "pointId")
);
ALTER TABLE "sourceReferenceInheritance" ADD CONSTRAINT source_inheritance_source_fk FOREIGN KEY ("sourceId") REFERENCES "medicalSource"(id) ON DELETE RESTRICT;
ALTER TABLE "sourceReferenceInheritance" ADD CONSTRAINT source_inheritance_point_fk FOREIGN KEY ("pointId") REFERENCES "analysisPoint"(id) ON DELETE RESTRICT;
CREATE INDEX min_reference_source_lookup_idx ON "analysisPointMinValue"("sourceId", "pointId", "ageId", "genderId", "unitId");
CREATE INDEX max_reference_source_lookup_idx ON "analysisPointMaxValue"("sourceId", "pointId", "ageId", "genderId", "unitId");
CREATE INDEX description_source_idx ON "analysisResultDescription"("sourceId");
`;
