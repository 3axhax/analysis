-- Проект для ревью; не является миграцией и не должен применяться напрямую.
-- Подключить к существующему runRecordedMigration после завершения адаптации API.
CREATE TABLE medical_source (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id integer REFERENCES medical_source(id) ON DELETE RESTRICT,
  name text NOT NULL CHECK (length(trim(name)) > 0),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX medical_source_parent_idx ON medical_source(parent_id);

ALTER TABLE "analysisPointMinValue" ADD COLUMN "sourceId" integer REFERENCES medical_source(id) ON DELETE RESTRICT;
ALTER TABLE "analysisPointMaxValue" ADD COLUMN "sourceId" integer REFERENCES medical_source(id) ON DELETE RESTRICT;
ALTER TABLE "analysisResultDescription" ADD COLUMN "sourceId" integer REFERENCES medical_source(id) ON DELETE RESTRICT;

CREATE TABLE source_reference_inheritance (
  source_id integer NOT NULL REFERENCES medical_source(id) ON DELETE RESTRICT,
  point_id integer NOT NULL REFERENCES "analysisPoint"(id) ON DELETE RESTRICT,
  PRIMARY KEY (source_id, point_id)
);
CREATE INDEX min_reference_source_lookup_idx ON "analysisPointMinValue"("sourceId", "pointId", "ageId", "genderId", "unitId");
CREATE INDEX max_reference_source_lookup_idx ON "analysisPointMaxValue"("sourceId", "pointId", "ageId", "genderId", "unitId");
CREATE INDEX description_source_idx ON "analysisResultDescription"("sourceId");
